const DICTS = { pl, en } as Record<Lang, Dict>

function readLang(): Lang {
  try {
    const v = localStorage.getItem(KEY)
    if (v === 'pl' || v === 'en') return v
  } catch {
    /* ignore */
  }
  return navigator.language?.startsWith('pl') ? 'pl' : 'en'
}

type Vars = Record<string, string | number>
const fill = (s: string, vars?: Vars) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : s)

interface I18n {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: Key, vars?: Vars) => string
  tList: (key: Key, vars?: Vars) => string[]
}

const Ctx = createContext<I18n | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(readLang)
  useEffect(() => {
    document.documentElement.lang = lang
    try {
      localStorage.setItem(KEY, lang)
    } catch {
      /* ignore */
    }
  }, [lang])
  const value = useMemo<I18n>(() => {
    const d = DICTS[lang]
    return {
      lang,
      setLang,
      t: (key, vars) => fill(d[key] as string, vars),
      tList: (key, vars) => (d[key] as readonly string[]).map((s) => fill(s, vars)),
    }
  }, [lang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n outside provider')
  return v
}
